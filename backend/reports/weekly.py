logger = get_logger(__name__)


class SyntheticDataRefused(RuntimeError):
    """Raised when a report would be built on synthetic data without acknowledgement."""


@dataclass
class ReportSection:
    key: str
    title: str
    body: str
    data: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {"key": self.key, "title": self.title, "body": self.body, "data": self.data}


@dataclass
class WeeklyReport:
    period_start: date
    period_end: date
    title: str
    sections: list[ReportSection] = field(default_factory=list)
    contains_synthetic: bool = False
    generated_by: str = "deterministic"

    def section(self, key: str) -> ReportSection | None:
        return next((s for s in self.sections if s.key == key), None)

    def to_markdown(self) -> str:
        lines = [f"# {self.title}", ""]
        if self.contains_synthetic:
            lines += [
                "> **⚠ SYNTHETIC DEMONSTRATION DATA**",
                "> Every figure in this report is fictional and corresponds to no real",
                "> security. This report exists to demonstrate the format only.",
                "",
            ]
        lines.append(
            f"*Period: {self.period_start.isoformat()} to {self.period_end.isoformat()} · "
            f"generated {datetime.now(timezone.utc).date().isoformat()} · "
            f"narrative by {self.generated_by}*"
        )
        lines.append("")
        for index, section in enumerate(self.sections, start=1):
            lines.append(f"## {index}. {section.title}")
            lines.append("")
            lines.append(section.body.strip())
            lines.append("")
        lines += [
            "---",
            "",
            "*EGX ALPHA is a personal research tool operating in paper-trading mode. "
            "Its output is generated by software and is not investment advice. Verify "
            "every figure against primary sources before acting on it.*",
        ]
        return "\n".join(lines)

    def to_dict(self) -> dict[str, Any]:
        return {
            "title": self.title,
            "period_start": self.period_start.isoformat(),
            "period_end": self.period_end.isoformat(),
            "contains_synthetic": self.contains_synthetic,
            "generated_by": self.generated_by,
            "sections": [s.to_dict() for s in self.sections],
        }


def _price_on_or_before(session: Session, ticker: str, on: date) -> float | None:
    bar = session.scalar(
        select(PriceBar)
        .where(PriceBar.ticker == ticker.upper(), PriceBar.timestamp <= on)
        .order_by(PriceBar.timestamp.desc())
    )
    if bar is None:
        return None
    return bar.close if bar.close is not None else bar.adjusted_close


def _period_return(
    session: Session, ticker: str, start: date, end: date
) -> float | None:
    first = _price_on_or_before(session, ticker, start)
    last = _price_on_or_before(session, ticker, end)
    if not first or not last or first <= 0:
        return None
    return (last - first) / first


def _pct(value: float | None, digits: int = 2) -> str:
    return "—" if value is None else f"{value:+.{digits}%}"


def _uses_synthetic(session: Session) -> bool:
    return session.scalar(
        select(PriceBar.source).where(PriceBar.source.like("SYNTHETIC%")).limit(1)
    ) is not None


def generate_weekly_report(
    session: Session,
    *,
    as_of: date | None = None,
    acknowledge_synthetic: bool = False,
    persist: bool = True,
) -> WeeklyReport:
    """Build the full ten-section investment committee report."""
    settings = get_settings()
    as_of = as_of or date.today()
    start = as_of - timedelta(days=7)
    synthetic = _uses_synthetic(session)

    if synthetic and not acknowledge_synthetic:
        raise SyntheticDataRefused(
            "This database contains SYNTHETIC DEMONSTRATION DATA. A report built on it "
            "would describe a fictional market. Pass acknowledge_synthetic=True to "
            "generate it for format demonstration only."
        )

    report = WeeklyReport(
        period_start=start,
        period_end=as_of,
        title=f"EGX ALPHA Weekly Investment Committee — {as_of.isoformat()}",
        contains_synthetic=synthetic,
    )

    portfolio = session.scalar(select(Portfolio).order_by(Portfolio.portfolio_id))
    benchmark_return = _period_return(session, settings.benchmark_ticker, start, as_of)

    report.sections.append(_section_executive_summary(session, start, as_of, benchmark_return))
    report.sections.append(_section_performance(session, portfolio, start, as_of, benchmark_return))
    winners, losers = _movers(session, start, as_of)
    report.sections.append(_section_movers("winners", "Biggest Winners", winners, session, start, as_of))
    report.sections.append(_section_movers("losers", "Biggest Losers", losers, session, start, as_of))
    report.sections.append(_section_opportunities(session, as_of))
    report.sections.append(_section_positions(session, portfolio, as_of))
    report.sections.append(_section_thesis_changes(session, as_of))
    report.sections.append(_section_risk(session, portfolio, as_of))
    report.sections.append(_section_macro(session, as_of))
    report.sections.append(_section_next_week(session, as_of))

    if persist:
        record = Report(
            report_type="weekly_committee",
            title=report.title,
            period_start=start,
            period_end=as_of,
            markdown=report.to_markdown(),
            sections=report.to_dict(),
            generated_by=report.generated_by,
            contains_synthetic_data=synthetic,
        )
        session.add(record)
        session.flush()
        log_event(
            logger, EVENT_REPORT, f"Weekly report generated for {as_of}",
            report_id=record.id, synthetic=synthetic,
        )
    return report


