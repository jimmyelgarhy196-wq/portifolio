"""Weekly investment committee report.

Generates the ten-section memo the brief specifies. Every figure comes from
stored data; where a section cannot be supported by data it says so rather than
producing filler.

The macro section is a deliberate exception, and an important one: this system
has no macroeconomic data feed, so it does **not** write about Egyptian rates,
inflation or FX. It states what it would need instead. Inventing a paragraph
about the macro environment would be exactly the fabrication the whole design
exists to prevent.
"""
